/**
 * After `vite build`, render every route to static HTML and write
 * sitemap.xml, robots.txt, _headers (Cloudflare Pages) and, only when an
 * AdSense publisher ID is configured, ads.txt.
 *
 *   dist/index.html                     → /
 *   dist/tools/image-resizer.html       → /tools/image-resizer
 *   dist/404.html                       → served with HTTP 404 by Cloudflare Pages
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const ssrDir = join(root, 'dist-ssr');

const template = await readFile(join(dist, 'index.html'), 'utf8');
if (!template.includes('<!--app-html-->') || !template.includes('<!--app-head-->')) {
  throw new Error('dist/index.html is missing the <!--app-head--> or <!--app-html--> placeholders.');
}
const { render, routes, canonicalUrl, site, adsEnabled, adsenseScriptEnabled } = await import(pathToFileURL(join(ssrDir, 'entry-server.js')).href);

const fill = (html, head) => template.replace('<!--app-head-->', head).replace('<!--app-html-->', html);
const outFile = (p) => (p === '/' ? join(dist, 'index.html') : join(dist, `${p.slice(1)}.html`));

let count = 0;
for (const route of routes) {
  const { html, head } = render(route.path);
  if (!html || html.length < 500) throw new Error(`Prerender produced empty HTML for ${route.path}`);
  const file = outFile(route.path);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, fill(html, head));
  count += 1;
}
{
  const { html, head } = render('/404');
  await writeFile(join(dist, '404.html'), fill(html, head));
}

// sitemap.xml
const lastmod = new Date().toISOString().slice(0, 10);
const urls = routes
  .filter((r) => r.indexable)
  .map(
    (r) =>
      `  <url>\n    <loc>${canonicalUrl(r.path)}</loc>\n    <lastmod>${lastmod}</lastmod>\n` +
      (r.changefreq ? `    <changefreq>${r.changefreq}</changefreq>\n` : '') +
      (r.priority !== undefined ? `    <priority>${r.priority.toFixed(1)}</priority>\n` : '') +
      '  </url>',
  )
  .join('\n');
await writeFile(join(dist, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`);

// robots.txt
await writeFile(join(dist, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site.origin}/sitemap.xml\n`);

// ads.txt only with a real publisher ID.
if (site.adsenseClient) {
  await writeFile(join(dist, 'ads.txt'), `google.com, ${site.adsenseClient.replace(/^ca-/, '')}, DIRECT, f08c47fec0942fa0\n`);
}

// _headers — security headers and caching for Cloudflare Pages.
// Google's ad code loads scripts, frames and beacons from many Google-owned
// hosts (including country domains such as adservice.google.co.nz), so when
// AdSense is present the CSP allows any https: origin for those directives.
// Everything else stays locked down.
const csp = adsenseScriptEnabled
  ? [
      "default-src 'self'",
      "script-src 'self' https:",
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' blob: data: https:",
      "font-src 'self'",
      "connect-src 'self' https:",
      "frame-src https:",
      "object-src 'none'",
      "base-uri 'self'",
      "form-action 'self'",
      "frame-ancestors 'none'",
    ].join('; ')
  : [
      "default-src 'self'",
      "script-src 'self'",
      "style-src 'self' 'unsafe-inline'",
      // https: is needed only for the sharing-preview "Show image" option.
      "img-src 'self' blob: data: https:",
      "font-src 'self'",
      "connect-src 'self'",
      "object-src 'none'",
      "base-uri 'self'",
      "form-action 'self'",
      "frame-ancestors 'none'",
    ].join('; ');

const headers = `# Generated by scripts/prerender.mjs — edit there, not here.
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()
  Cross-Origin-Opener-Policy: ${adsenseScriptEnabled ? 'same-origin-allow-popups' : 'same-origin'}
  Content-Security-Policy: ${csp}
  Cache-Control: public, max-age=0, must-revalidate

/ads.txt
  Content-Type: text/plain; charset=utf-8

# Hashed build assets never change.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

# Keep *.pages.dev preview and production aliases out of search results.
https://:project.pages.dev/*
  X-Robots-Tag: noindex

https://:version.:project.pages.dev/*
  X-Robots-Tag: noindex
`;
await writeFile(join(dist, '_headers'), headers);

await rm(ssrDir, { recursive: true, force: true });
console.log(
  `Prerendered ${count} routes + 404.html; wrote sitemap.xml, robots.txt, _headers${site.adsenseClient ? ', ads.txt' : ''}. AdSense script ${adsenseScriptEnabled ? 'ON' : 'off'}; ad units ${adsEnabled ? 'ENABLED' : 'off (no slot ID)'}.`,
);
if (!site.contactEmail) console.warn('WARNING: VITE_CONTACT_EMAIL is not set — the contact page has no address (needed before AdSense review).');
